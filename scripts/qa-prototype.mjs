// تدفق النموذج التفاعلي من البداية للنهاية: Onboarding → دخول → OTP → الرئيسية → المتجر → + → السلة (حساب دقيق) → تأكيد الطلب
const PW = process.env.PLAYWRIGHT_PATH || '/home/user/.npm/_npx/f0a362733743bae2/node_modules/playwright/index.mjs'
const { chromium } = await import(PW)
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1400, height: 980 } })
const errors = []; page.on('console', m => { if (['error','warning'].includes(m.type())) errors.push(m.text()) }); page.on('pageerror', e => errors.push(String(e)))
const phone = () => page.locator('div[style*="width: 390px"]').first()
const T = (ms) => page.waitForTimeout(ms)
const has = (t) => phone().getByText(t, { exact: false }).first().isVisible().catch(() => false)
const R = []; const check = (n, ok, x = '') => { R.push(ok); console.log(`${ok ? 'PASS' : 'FAIL'} | ${n}${x ? ' — ' + x : ''}`) }
await page.goto('http://localhost:5173/#/prototype'); await T(3600)
await phone().getByRole('button', { name: 'تخطي', exact: true }).click(); await T(400)
await phone().getByRole('button', { name: /متسوق \(مشتري\)/ }).click(); await T(200)
await phone().getByRole('button', { name: 'متابعة', exact: true }).click(); await T(500)
await phone().locator('input').first().fill('773030064'); await phone().getByRole('button', { name: /إرسال رمز/ }).click(); await T(500)
await phone().getByRole('button', { name: /الانتقال لإدخال/ }).click(); await T(400)
const otp = phone().locator('input'); for (let i = 0; i < 4; i++) await otp.nth(i).fill(String(i + 1)); await T(700)
await phone().getByRole('button', { name: /المتابعة للرئيسية/ }).click(); await T(600)
check('الدخول → الرئيسية', await has('الأقسام والتصنيفات'))
await phone().getByRole('button', { name: /متجر التكنولوجيا الحديثة/ }).first().click(); await T(600)
check('بطاقة المتجر → شاشة تفاصيل المتجر وقائمة المنتجات', await has('قائمة منتجات المتجر'))
await phone().getByRole('button', { name: /أضف سماعات/ }).click(); await T(150)
await phone().getByRole('button', { name: /أضف سماعات/ }).click(); await T(150)
await phone().getByRole('button', { name: /أضف ساعة/ }).click(); await T(300)
check('زر + يضيف فعلياً (شارة 2)', (await phone().getByRole('button', { name: /أضف سماعات/ }).innerText()).trim() === '2')
await phone().getByRole('button', { name: 'العودة إلى الرئيسية' }).click(); await T(500)
check('«العودة إلى الرئيسية» وشارة السلة = 3', await has('الأقسام والتصنيفات') && (await phone().getByLabel('السلة').innerText()).trim() === '3')
await phone().getByLabel('السلة').click(); await T(500)
const txt = await phone().innerText(); check('السلة: 2×34,500 + 18,200 = 87,200', /87,200/.test(txt))
await phone().getByRole('button', { name: /إتمام الطلب|الدفع|متابعة الشراء/ }).first().click(); await T(500)
await phone().getByRole('button', { name: /تأكيد|ادفع|إتمام/ }).last().click(); await T(1500)
check('تأكيد الطلب → نجاح برقم JD-', await has('JD-'))
console.log('console errors:', errors.length ? errors : 'none')
console.log(`══ ${R.filter(Boolean).length}/${R.length} PASS ══`)
await browser.close(); process.exit(R.every(Boolean) && !errors.length ? 0 : 1)
